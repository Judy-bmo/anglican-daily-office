import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'

/**
 * PDF는 양쪽 맞추기 조판이라 줄 끝에 공백 글리프가 남지 않는다. 그래서 줄이
 * 어절 중간에서 끊겼는지 어절 경계에서 끊겼는지를 통계로 판정한다
 * (tools/joinwords.py). 앞 토막이 한 글자뿐이고 뒤 토막이 홀로는 쓰이지 않는
 * 낱말일 때 판정이 띄우는 쪽으로 기울어 '불 리우는'처럼 갈라지는 일이 있었다.
 *
 * 819쪽의 줄바꿈 7,984곳을 공동번역 성서 57만 어절과 견주어 43곳을 바로잡았다.
 * 데이터를 다시 뽑을 때 그 표가 빠지면 여기서 걸린다.
 */
const text = ['public/data/offices.json', 'public/data/psalter.json']
  .map((p) => readFileSync(p, 'utf8'))
  .join('\n')

// 바로잡은 43곳 가운데 사람이 눈으로 확인한 것들
const 갈라졌던_곳: Array<[string, string]> = [
  ['불 리우는', '불리우는'],
  ['아 니하리라', '아니하리라'],
  ['하 느님이시다', '하느님이시다'],
  ['세 우셨습니다', '세우셨습니다'],
  ['아 들이시나', '아들이시나'],
  ['분 이시어라', '분이시어라'],
  ['도 망쳐라', '도망쳐라'],
  ['말 지니라', '말지니라'],
  ['속 량하셨습니다', '속량하셨습니다'],
  ['설 레설레', '설레설레'],
  ['나 서넋을잃고', '나서 넋을 잃고'],
]

describe('줄바꿈으로 갈라졌던 낱말', () => {
  for (const [갈라진꼴, 바른꼴] of 갈라졌던_곳) {
    it(`${갈라진꼴} → ${바른꼴}`, () => {
      expect(text).not.toContain(갈라진꼴)
      expect(text).toContain(바른꼴)
    })
  }

  it('한 글자가 홀로 떨어져 나온 자리가 남아 있지 않다', () => {
    // 앞말이 한 글자짜리 낱말이고 뒷말이 홀로 못 서는 토막으로 시작하는 꼴.
    // ('주께서 밟으신'처럼 앞말이 여러 글자인 것은 정상이므로 뒤돌아보기로 제외한다)
    const 의심 = text.match(/(?<![가-힣])[가-힣] (?:이시|니하|느님|드셨|드소|라진|라질|았구|았습|러앉|려받|밟으|아지들)/g)
    expect(의심 ?? []).toEqual([])
  })
})
